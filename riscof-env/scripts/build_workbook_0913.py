#!/usr/bin/env python3
"""Research_data_RISCOF_with_cores_0902.xlsx -> Research_data_complete_0908.xlsx

Each SoC project is implemented with ONE benchmark image in ROM, and the image
changes the LUT count -- which is why the workbook keeps a separate "SoC
Dhrystone" and "SoC Coremark" block.  The Sep 8 sweep measured whatever image
each project currently holds, so each variant updates exactly one row, in
whichever block matches its image.  Rows in the other block keep their Sep 1/2
values and are labelled as such rather than being overwritten with a number
that was never measured for that image.
"""
import csv, json, pathlib, shutil, datetime
import openpyxl
from openpyxl.styles import PatternFill, Font, Alignment

ENV  = pathlib.Path(__file__).resolve().parent.parent
SRC  = pathlib.Path.home() / "Documents" / "Research_data_RISCOF_with_cores_0902.xlsx"
DST  = pathlib.Path.home() / "Documents" / "Research_data_complete_0913.xlsx"
CSV  = ENV / "logs" / "impl_retime.csv"

# Each SoC project holds ONE benchmark image, and the image changes the design,
# so the workbook keeps a "SoC Dhrystone" block (rows 13-20) and a "SoC Coremark"
# block (rows 23-30).  A variant sits in whichever block matches the image it
# holds; swapping the image moves it to the mirrored row, ten rows away.
#
# PRE  = measured 2026-09-08 with the image each project held then.
# POST = measured 2026-09-09 after swapping every project to the other benchmark.
# Both are real measurements, so both blocks are populated.
# the pre-swap CSV kept only the workbook columns; clock and WNS come from the
# verified Sep-8 figures recorded in STATUS.md
pre_clk = {"RV32I_5SP":45.0,"RV32IM_5SP":43.0,"RV32IM_6SP":50.0,"RV32IM_7SP":58.0,
 "RV32IM_7SP_BRAM":72.0,"RV32IM_7SP_BRAM_Opt":90.909,"RV32IM_8SP_withoutOpt":114.0,
 "RV32IM_8SP":125.0,"RV64I_5SP":40.0,"RV64IM_5SP":38.0,"RV64IM_6SP":45.0,
 "RV64IM_7SP":48.612,"RV64IM_7SP_BRAM":55.0,"RV64IM_7SP_BRAM_Opt":84.0,
 "RV64IM_8SP_withoutOpt":96.0,"RV64IM_8SP":100.0}
pre_wns = {"RV32I_5SP":0.137,"RV32IM_5SP":0.074,"RV32IM_6SP":0.028,"RV32IM_7SP":-0.005,
 "RV32IM_7SP_BRAM":0.091,"RV32IM_7SP_BRAM_Opt":0.092,"RV32IM_8SP_withoutOpt":0.023,
 "RV32IM_8SP":-0.223,"RV64I_5SP":0.052,"RV64IM_5SP":0.040,"RV64IM_6SP":0.053,
 "RV64IM_7SP":-0.242,"RV64IM_7SP_BRAM":0.239,"RV64IM_7SP_BRAM_Opt":0.003,
 "RV64IM_8SP_withoutOpt":-0.444,"RV64IM_8SP":0.160}

PRE = {
    "RV64I_5SP":            ("Sheet1", 13), "RV64IM_7SP_BRAM_Opt": ("Sheet1", 18),
    "RV64IM_8SP":           ("Sheet1", 20), "RV64IM_5SP":          ("Sheet1", 24),
    "RV64IM_6SP":           ("Sheet1", 25), "RV64IM_7SP":          ("Sheet1", 26),
    "RV64IM_7SP_BRAM":      ("Sheet1", 27), "RV64IM_8SP_withoutOpt": ("Sheet1", 29),
    "RV32IM_5SP":           ("Sheet2", 14), "RV32IM_7SP_BRAM":     ("Sheet2", 17),
    "RV32IM_7SP_BRAM_Opt":  ("Sheet2", 18), "RV32IM_8SP_withoutOpt": ("Sheet2", 19),
    "RV32IM_8SP":           ("Sheet2", 20), "RV32I_5SP":           ("Sheet2", 23),
    "RV32IM_6SP":           ("Sheet2", 25), "RV32IM_7SP":          ("Sheet2", 26),
}
mirror = lambda r: r + 10 if r <= 20 else r - 10

COL = dict(lut="C", lutram="D", ff="E", bram="F", dsp="G", io="H", pll="I", fmax="J",
           p_clocks="M", p_signals="N", p_logic="O", p_bram="P", p_dsp="Q",
           p_pll="R", p_io="S", p_static="T", note="U")

# Colour only where there is something to act on.  A fill on every row -- the old
# green-for-normal -- is noise: it makes the sheet look busy and hides the rows
# that actually need attention.
RED   = PatternFill("solid", fgColor="FFC7CE")   # timing VIOLATION at the configured clock
BLUE  = PatternFill("solid", fgColor="BDD7EE")   # >1 MHz headroom: build a faster .mem
GREEN = PatternFill(fill_type=None)              # timing met, nothing to do -> no fill
GREY  = PatternFill("solid", fgColor="FFEB9C")   # not measured / needs checking

pre_data  = {r["variant"]: r for r in csv.DictReader(
    (ENV / "logs" / "impl_retime_preswap_full.csv").open())}
# frozen snapshot of the post-swap pass.  logs/impl_retime.csv is the LIVE
# measurement file and gets regenerated by every later sweep, so reading it
# here silently back-dated new results into the swap rows.
post_data = {r["variant"]: r for r in csv.DictReader(
    (ENV / "logs" / "soc_postswap.csv").open())}
plan      = {p["variant"]: p for p in json.load((ENV / "logs" / "swap_plan.json").open())}

shutil.copy(SRC, DST)
wb = openpyxl.load_workbook(DST)

num = lambda v: float(v) if v not in (None, "", "None") else None
soc_rows, headroom, failing = [], [], []

def write_row(ws, row, d, image, when, is_post):
    """Write one SoC row and colour its Fmax by timing outcome."""
    for key, col in COL.items():
        if key == "note":
            continue
        src_key = "fmax_mhz" if key == "fmax" else key
        raw = d.get(src_key)
        if raw in (None, "", "None"):
            continue
        ws[f"{col}{row}"] = (float(raw) if key.startswith("p_") or key == "fmax"
                             else int(float(raw)))
    fmax = float(d["fmax_mhz"])
    clk  = float(d["constraint_mhz"]) if d.get("constraint_mhz") else None
    wns  = float(d["wns_ns"]) if d.get("wns_ns") not in (None, "", "None") else None
    head = (fmax - clk) if clk is not None else None
    tag  = ""
    # hold the PatternFill in a local: reading back cell.fill yields a StyleProxy,
    # which openpyxl cannot assign to another cell
    if wns is not None and wns < 0:
        fill = RED
        tag = (f"  ||  TIMING NOT MET at {clk} MHz (WNS {wns:+.3f} ns) - the design only "
               f"closes at {fmax:.2f} MHz; needs a slower image or re-timing")
    elif head is not None and head > 1.0:
        fill = BLUE
        tag = (f"  ||  HEADROOM +{head:.2f} MHz - runs at {clk} MHz but closes at "
               f"{fmax:.2f} MHz; a faster .mem image is worth building")
    else:
        fill = GREEN
    ws[f"J{row}"].fill = fill
    ws[f"U{row}"] = f"{when}; image {image}" + (
        f"; clock {clk} MHz, WNS {wns:+.3f} ns" if wns is not None else "") + tag
    ws[f"U{row}"].fill = fill          # memo carries the same status colour
    return head, wns

for v, (sheet, row) in PRE.items():
    ws = wb[sheet]
    # --- pre-swap row (2026-09-08) ---
    d = pre_data[v]
    d = {**d, "constraint_mhz": pre_clk.get(v), "wns_ns": pre_wns.get(v)}
    h, w = write_row(ws, row, d, plan[v]["cur"],
                     "measured 2026-09-08 on the fully-verified RTL", False)
    soc_rows.append((v, sheet, row))
    if w is not None and w < 0:
        failing.append((f"{v} [{sheet[-1]}:r{row}]", pre_clk[v], float(d["fmax_mhz"]), h))
    elif h is not None and h > 1.0:
        headroom.append((f"{v} [{sheet[-1]}:r{row}]", pre_clk[v], float(d["fmax_mhz"]), h))
    # --- post-swap row (2026-09-09), mirrored block ---
    if plan[v]["action"] != "swap":
        prow = mirror(row)
        ws[f"J{prow}"].fill = GREY
        ws[f"U{prow}"] = ("NOT measured - this variant was not swapped (no benchmark image "
                          "exists at or below its Fmax), so it has never run this benchmark "
                          "on the fixed RTL.  || " + (ws[f"U{prow}"].value or ""))
        ws[f"U{prow}"].fill = GREY
        continue
    prow = mirror(row)
    h, w = write_row(ws, prow, post_data[v], plan[v]["tgt"],
                     "measured 2026-09-09 after the benchmark swap", True)
    soc_rows.append((v, sheet, prow))
    if w is not None and w < 0:
        failing.append((f"{v} [{sheet[-1]}:r{prow}]", float(post_data[v]["constraint_mhz"]),
                        float(post_data[v]["fmax_mhz"]), h))
    elif h is not None and h > 1.0:
        headroom.append((f"{v} [{sheet[-1]}:r{prow}]", float(post_data[v]["constraint_mhz"]),
                         float(post_data[v]["fmax_mhz"]), h))

# ------------------------------------------------- latest layer (2026-09-09 pm)
# After the swap, every violating or over-relaxed row was re-imaged at a
