n_time = 0
if MAN.is_file():
    man = {(r["variant"], r["benchmark"]): r for r in csv.DictReader(MAN.open())}
    for sheet in ("Sheet1", "Sheet2"):
        ws = wb[sheet]
        for bench, base in (("dhrystone", 13), ("coremark", 23)):
            for i, short in enumerate(ORDER8):
                row = base + i
                pfx = "RV64" if sheet == "Sheet1" else "RV32"
